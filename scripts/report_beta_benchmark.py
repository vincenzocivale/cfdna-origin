#!/usr/bin/env python3
"""Consolidated report of the processed-beta pilot -> docs/BETA_BENCHMARK_RESULTS.md (+ CSVs in the outputs tree).

  python scripts/report_beta_benchmark.py [--n-boot 2000]

For each experiment: per-arm metrics (mean ± sd over repetition seeds, and the seed ensemble of out-of-fold
predictions), paired patient-level comparisons (bootstrap CI + permutation p), per-fold/seed win rates of functional over
each control, per-batch metrics; batch-prediction negative control; per-sample loci/coverage diagnostics vs class, batch
and prediction confidence; attribution summary. Only completed runs are read.
"""
from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd
from scipy import stats

from cfdna_origin.config import REPO_ROOT, load_experiment, load_paths
from cfdna_origin.evaluation.summary import collect, summarize
from cfdna_origin.experiments.beta_runner import load_beta, task_samples

TISSUE = {"A. all_classes_original": "beta_all_classes", "B. exclude_crc": "beta_exclude_crc",
          "C. batch_robust_subset": "beta_batch_robust"}
BATCH = {"all_classes_original": "beta_batchpred_all_classes_original", "exclude_crc": "beta_batchpred_exclude_crc"}
ARM_ORDER = ["methylation_only", "summary_only", "position_only", "random", "functional_shuffled", "functional",
             "ntv3_pre", "dmr_logistic", "dmr_xgboost"]
DIAG = ["n_observed_loci", "missing_fraction", "mean_beta", "beta_variance", "mean_coverage"]


def fmt(m, s):
    return "–" if pd.isna(m) else (f"{m:.3f}" if pd.isna(s) else f"{m:.3f} ± {s:.3f}")


def win_rates(runs: pd.DataFrame, ref: str = "functional") -> pd.DataFrame:
    """Share of (seed, fold) cells where `ref` beats each other arm (paired on the same test patients)."""
    piv = runs.pivot_table(index=["seed", "fold"], columns="representation", values="test_macro_f1")
    out = []
    for arm in piv.columns:
        if arm == ref or ref not in piv:
            continue
        d = (piv[ref] - piv[arm]).dropna()
        out.append({"arm": arm, "cells": len(d), "functional_wins": int((d > 0).sum()), "mean_delta_macro_f1": d.mean()})
    return pd.DataFrame(out)


def experiment_block(name: str, paths: dict, n_boot: int):
    exp = load_experiment(name)
    exp_dir = paths["outputs_root"] / exp["dataset"]["name"] / exp["name"]
    if not exp_dir.exists():
        return None
    _, classes = task_samples(exp, load_beta(exp, paths))
    res = summarize(exp_dir, classes, exp["seeds"], exp["folds"], [tuple(p) for p in exp.get("comparisons", [])],
                    n_boot=n_boot, n_perm=n_boot)
    res["win"] = win_rates(res["runs"])
    res["classes"] = classes
    res["exp_dir"] = exp_dir
    return res


def arm_table(res) -> str:
    a = res["arms"].set_index("representation")
    rows = ["| arm | macro-F1 | balanced acc | AUROC (macro OvR) | accuracy | ensemble macro-F1 | complete |",
            "|---|---|---|---|---|---|---|"]
    for arm in [x for x in ARM_ORDER if x in a.index] + [x for x in a.index if x not in ARM_ORDER]:
        r = a.loc[arm]
        rows.append(f"| {arm} | {fmt(r.macro_f1_mean, r.macro_f1_sd)} | {fmt(r.balanced_accuracy_mean, r.balanced_accuracy_sd)} "
                    f"| {fmt(r.auroc_macro_mean, r.auroc_macro_sd)} | {fmt(r.accuracy_mean, r.accuracy_sd)} "
                    f"| {fmt(r.get('macro_f1_seed_ensemble', np.nan), np.nan)} | {'yes' if r.complete else 'NO'} |")
    return "\n".join(rows)


def comparison_table(res) -> str:
    c = res["comparisons"]
    if c.empty:
        return "(no complete pair)"
    rows = ["| functional vs | metric | Δ (functional − control) | 95% CI | permutation p |", "|---|---|---|---|---|"]
    for _, r in c.iterrows():
        rows.append(f"| {r.arm_b} | {r.metric} | {r.delta:+.3f} | [{r.ci95_low:+.3f}, {r.ci95_high:+.3f}] | {r.p_perm_two_sided:.3f} |")
    return "\n".join(rows)


def diagnostics(res) -> pd.DataFrame:
    """Spearman correlation of per-sample covariates with prediction confidence (test OOF, pooled seeds)."""
    _, preds = collect(res["exp_dir"])
    t = preds[preds.split == "test"]
    cols = [c for c in t.columns if c.startswith("prob_")]
    t = t.assign(confidence=t[cols].max(1))
    out = []
    for arm, g in t.groupby("representation"):
        row = {"arm": arm}
        for v in DIAG:
            rho, p = stats.spearmanr(g[v], g.confidence)
            row[f"rho_{v}"] = rho; row[f"p_{v}"] = p
        out.append(row)
    return pd.DataFrame(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n-boot", type=int, default=2000)
    args = ap.parse_args()
    paths = load_paths()
    lines = ["# Processed-beta pilot: results", "",
             "Generated by `scripts/report_beta_benchmark.py`. Sample-level only; out-of-fold test predictions of "
             "patient-level repeated stratified CV (5 folds x 3 repetition seeds; cross-batch for protocol C). "
             "Metrics are mean ± sd over repetition seeds (each seed predicts every patient once). Comparisons use the "
             "seed-averaged out-of-fold probabilities per patient, with a paired patient-level stratified bootstrap "
             f"({args.n_boot} resamples) and a paired permutation test. CpGs are never resampled.", ""]
    tissue = {}
    for title, name in TISSUE.items():
        res = experiment_block(name, paths, args.n_boot)
        if res is None:
            lines += [f"## {title}", "", "(not run)", ""]; continue
        tissue[title] = res
        lines += [f"## {title}  (`{name}`; classes: {', '.join(res['classes'])})", "", arm_table(res), "",
                  "Paired comparisons (patient-level):", "", comparison_table(res), "",
                  "Per (seed, fold) cell: how often functional beats each arm on test macro-F1:", "",
                  res["win"].round(3).to_markdown(index=False) if not res["win"].empty else "(n/a)", ""]
        if res["incomplete"]:
            lines += [f"Incomplete arms (excluded from comparisons): {res['incomplete']}", ""]
        pb = res["per_batch"]
        if not pb.empty:
            agg = pb.groupby(["representation", "batch"])[["balanced_accuracy", "accuracy"]].mean().unstack().round(3)
            lines += ["Per-batch metrics (mean over seeds):", "", agg.to_markdown(), ""]
    lines += ["## Batch-prediction negative control (KRp1 vs KRp2)", "",
              "The same inputs, models and splits are used, with the batch as label. This is a confounding diagnostic, "
              "not a task.", ""]
    for proto, name in BATCH.items():
        res = experiment_block(name, paths, args.n_boot)
        if res is None:
            lines += [f"### {proto}: (not run)", ""]; continue
        a = res["arms"].set_index("representation")
        lines += [f"### {proto}", "", "| arm | batch AUROC | batch balanced acc | batch macro-F1 |", "|---|---|---|---|"]
        for arm in [x for x in ARM_ORDER if x in a.index]:
            r = a.loc[arm]
            lines.append(f"| {arm} | {fmt(r.auroc_macro_mean, r.auroc_macro_sd)} | "
                         f"{fmt(r.balanced_accuracy_mean, r.balanced_accuracy_sd)} | {fmt(r.macro_f1_mean, r.macro_f1_sd)} |")
        lines += ["", comparison_table(res), ""]
    if "A. all_classes_original" in tissue:
        d = diagnostics(tissue["A. all_classes_original"])
        lines += ["## Loci-count / coverage diagnostics (protocol A, test predictions)", "",
                  "Spearman correlation between per-sample covariates and prediction confidence (max probability):", "",
                  d.round(3).to_markdown(index=False), "",
                  "Associations of the same covariates with class and batch are in `docs/GSE149438_BATCH_AUDIT.md`.", ""]
        att = list(tissue["A. all_classes_original"]["exp_dir"].glob("functional/seed_*/fold_*/attributions.parquet"))
        if att:
            a = pd.concat([pd.read_parquet(p) for p in att])
            top = (a.groupby(["predicted_class", "chrom_code", "pos_hg38"]).size().rename("n_samples_in_top_k")
                   .reset_index().sort_values(["predicted_class", "n_samples_in_top_k"], ascending=[True, False])
                   .groupby("predicted_class").head(10))
            out = tissue["A. all_classes_original"]["exp_dir"] / "summary" / "functional_attribution_top_loci.csv"
            top.to_csv(out, index=False)
            lines += ["## Functional attribution (interpretation only; never used for training)", "",
                      f"Top loci by recurrence in the per-sample top-{int(a.groupby('sample_id').size().max())} "
                      f"contribution lists (seed 17, test folds). Full table: `{out.name}`.", "",
                      top.to_markdown(index=False), ""]
    (REPO_ROOT / "docs" / "BETA_BENCHMARK_RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
